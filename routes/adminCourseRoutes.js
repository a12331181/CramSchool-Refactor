const { Router } = require('express')
const { authenticatedAdmin } = require('../middlewares/auth')
const adminCalendarController = require('../controllers/adminCalendarController')
const adminCourseController = require('../controllers/adminCourseController')

const router = Router()

router.get('/', authenticatedAdmin, adminCourseController.getCourses)
router.get('/create', authenticatedAdmin, adminCourseController.getCreateCoursePage)
router.post('/', authenticatedAdmin, adminCourseController.postCourse)
router.get('/:id/edit', authenticatedAdmin, adminCourseController.editCourse)
router.put('/:id/close', authenticatedAdmin, adminCourseController.closeCourse)
router.put('/:id/open', authenticatedAdmin, adminCourseController.openCourse)
router.put('/:id', authenticatedAdmin, adminCourseController.putCourse)
router.delete('/:id', authenticatedAdmin, adminCourseController.deleteCourse)
router.get('/:id/calendar', authenticatedAdmin, adminCalendarController.getCourseCalendar)
router.get('/:courseId/sessions/create', authenticatedAdmin, adminCalendarController.getCreateCourseSessionPage)
router.get('/:courseId/calendar/:calendarId/edit', authenticatedAdmin, adminCalendarController.getLegacyCalendarEditPage)
router.post('/:courseId/sessions', authenticatedAdmin, adminCalendarController.createCourseSession)
router.get('/:courseId/sessions/batch/create', authenticatedAdmin, adminCalendarController.getCreateCourseSessionBatchPage)
router.post('/:courseId/sessions/batch', authenticatedAdmin, adminCalendarController.createCourseSessionBatch)
router.put('/:courseId/sessions/:calendarId/cancel', authenticatedAdmin, adminCalendarController.cancelCourseSession)
router.put('/:courseId/sessions/:calendarId/complete', authenticatedAdmin, adminCalendarController.completeCourseSession)
router.put('/:courseId/calendar/:calendarId', authenticatedAdmin, adminCalendarController.updateLegacyCalendar)

module.exports = router
